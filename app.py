"""Lookout entry point: discovers reports and builds the landing page and navigation.

Do not edit this file to add a report. Drop a file into ``reports/`` instead
(copy ``reports/_template.py``).
"""

from __future__ import annotations

import streamlit as st

from ui.components import report_errors, report_tiles
from ui.discovery import by_category, discover_reports


def main() -> None:
    st.set_page_config(page_title="Lookout", page_icon="🔭", layout="wide")
    specs, errors = discover_reports()

    pages = {
        spec.slug: st.Page(spec.render, title=spec.title, icon=spec.icon, url_path=spec.slug)
        for spec in specs
    }

    def home() -> None:
        st.title("🔭 Lookout")
        st.caption("Read-only checks of trading setups in TT. Lookout never changes anything.")
        report_tiles(specs, pages)
        report_errors(errors)

    home_page = st.Page(home, title="Home", icon="🏠", url_path="home", default=True)
    sections = {"": [home_page]}
    for category, group in by_category(specs).items():
        sections[category] = [pages[spec.slug] for spec in group]
    st.navigation(sections).run()


main()
